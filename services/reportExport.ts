const SEV_RGB: Record<Severity, [number, number, number]> = { Critical: [220, 38, 38], High: [234, 88, 12], Medium: [202, 138, 4], Low: [5, 150, 105] };

export const reportToPdf = (r: ShiftReport, opts: ReportExportOptions): Blob => {
  const pdf = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = pdf.internal.pageSize.getWidth();
  const H = pdf.internal.pageSize.getHeight();
  const M = 48;
  const CW = W - M * 2;
  const BOTTOM = H - 56;
  let y = M;
  const shift = getShift(r.shift);
  const m = computeMetrics([r], null);

  const ensure = (h: number) => { if (y + h > BOTTOM) { pdf.addPage(); y = M; } };
  const text = (t: string, size = 10, style: 'normal' | 'bold' | 'italic' = 'normal', color: [number, number, number] = [24, 24, 27], indent = 0) => {
    pdf.setFont('helvetica', style); pdf.setFontSize(size); pdf.setTextColor(...color);
    const lines: string[] = pdf.splitTextToSize(t || '', CW - indent);
    const lh = size * 1.35;
    lines.forEach(line => { ensure(lh); pdf.text(line, M + indent, y + size); y += lh; });
  };
  const heading = (t: string) => {
    ensure(34); y += 10;
    pdf.setDrawColor(228, 228, 231); pdf.setLineWidth(1);
    text(t, 13, 'bold', [11, 18, 32]);
    pdf.line(M, y + 2, W - M, y + 2); y += 8;
  };
  const kv = (k: string, v: string) => {
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.setTextColor(82, 82, 91);
    ensure(14); pdf.text(k, M, y + 9);
    pdf.setFont('helvetica', 'normal'); pdf.setTextColor(24, 24, 27);
    const lines: string[] = pdf.splitTextToSize(v || '—', CW - 120);
    lines.forEach((l, i) => { if (i) ensure(13); pdf.text(l, M + 120, y + 9); y += 13; });
  };
  const custom = (pos: CustomSection['position']) => sections(opts, pos).forEach(s => {
    heading(s.heading || 'Note'); text(s.content, 10);
  });

  // Title band
  pdf.setFillColor(11, 18, 32); pdf.rect(0, 0, W, 96, 'F');
  pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8); pdf.setTextColor(252, 165, 165);
  pdf.text(opts.classification.toUpperCase(), M, 28);
  pdf.setFontSize(18); pdf.setTextColor(255, 255, 255);
  pdf.text(pdf.splitTextToSize(reportTitle(r, opts), CW)[0], M, 54);
  pdf.setFont('helvetica', 'normal'); pdf.setFontSize(10); pdf.setTextColor(165, 180, 252);
  pdf.text(`${opts.subtitle} · ${opts.organization}`, M, 74);
  y = 116;

  custom('header');
  kv('Report ID', r.id);
  kv('Date / Shift', `${r.date} · ${shift.label} (${shift.timing})`);
  kv('Status', r.status.toUpperCase());
  kv('Created', `${fmt(r.createdAt)} by ${r.createdBy}`);
  kv('Finalized', r.finalizedAt ? `${fmt(r.finalizedAt)} by ${r.finalizedBy}` : 'Draft — not sealed');
  kv('Contributors', (r.contributors || []).join(', '));
  kv('Prepared by', opts.preparedBy);

  if (opts.includeAnalytics) {
    heading('Threat Metrics');
    kv('Total events', String(m.totalEvents));
    kv('Criticality index', `${m.criticalityIndex}% (High + Critical)`);
    kv('Severity', SEVERITIES.map(s => `${s}: ${m.bySeverity[s]}`).join('   '));
    kv('Top attack vector', m.topAttackTypes[0] ? `${m.topAttackTypes[0].name} (${m.topAttackTypes[0].count})` : '—');
    kv('Primary hostile IP', m.topSourceIps[0] ? `${m.topSourceIps[0].name} (${m.topSourceIps[0].count})` : '—');
    // severity bar
    ensure(24); y += 6;
    let x = M;
    SEVERITIES.forEach(s => {
      const w = m.totalEvents ? (m.bySeverity[s] / m.totalEvents) * CW : 0;
      if (w > 0) { pdf.setFillColor(...SEV_RGB[s]); pdf.rect(x, y, w, 8, 'F'); x += w; }
    });
    if (!m.totalEvents) { pdf.setFillColor(228, 228, 231); pdf.rect(M, y, CW, 8, 'F'); }
    y += 16;
  }

  if (r.summary) { heading('Shift Summary'); text(r.summary); }

  heading('Event Log');
  if (!r.events.length) text('No events recorded during this shift.', 10, 'italic', [113, 113, 122]);
  else {
    const cols = [{ h: 'Time', w: 44 }, { h: 'Severity', w: 56 }, { h: 'Event', w: 140 }, { h: 'Source IP', w: 92 }, { h: 'Destination IP', w: 92 }, { h: 'Port', w: CW - 424 }];
    const row = (vals: string[], bold: boolean, sev?: Severity) => {
      pdf.setFont('helvetica', bold ? 'bold' : 'normal'); pdf.setFontSize(8.5);
      const wrapped = vals.map((v, i) => pdf.splitTextToSize(v || '—', cols[i].w - 6) as string[]);
      const h = Math.max(...wrapped.map(w => w.length)) * 11 + 6;
      ensure(h);
      if (bold) { pdf.setFillColor(244, 244, 245); pdf.rect(M, y, CW, h, 'F'); }
      let x = M;
      wrapped.forEach((lines, i) => {
        pdf.setTextColor(...(i === 1 && sev ? SEV_RGB[sev] : [24, 24, 27] as [number, number, number]));
        lines.forEach((l, li) => pdf.text(l, x + 3, y + 11 + li * 11));
        x += cols[i].w;
      });
      pdf.setDrawColor(228, 228, 231); pdf.line(M, y + h, W - M, y + h);
      y += h;
    };
    row(cols.map(c => c.h), true);
    r.events.forEach(e => row([fmtTime(e.timestamp), e.severity, e.eventName, e.sourceIp, e.destinationIp, e.port], false, e.severity));
  }

  if (opts.includeEventDetails && r.events.length) {
    heading('Investigation & Remediation Details');
    r.events.forEach((e, i) => {
      ensure(40); y += 4;
      text(`${i + 1}. ${e.eventName} — ${e.severity}`, 11, 'bold', SEV_RGB[e.severity]);
      text(`${fmt(e.timestamp)} · ${e.attackType || 'Unclassified'} · logged by ${e.loggedBy} · ${e.sourceIp || '?'} -> ${e.destinationIp || '?'}${e.port ? ':' + e.port : ''} ${e.protocol || ''}`, 8.5, 'italic', [113, 113, 122]);
      if (e.investigation) { text('Investigation / Forensic Findings', 9, 'bold', [63, 63, 70], 8); text(e.investigation, 9.5, 'normal', [24, 24, 27], 8); }
      if (e.remediation) { text('Remediation', 9, 'bold', [63, 63, 70], 8); text(e.remediation, 9.5, 'normal', [24, 24, 27], 8); }
      if (e.conclusion) { text('SOC Conclusion', 9, 'bold', [63, 63, 70], 8); text(e.conclusion, 9.5, 'normal', [24, 24, 27], 8); }
    });
  }

  custom('body');
  if (r.handoverNotes) { heading('Shift Handover Notes'); text(r.handoverNotes); }
  if (opts.includeIntegrity) {
    heading('Record Integrity');
    if (r.integrityHash) { text('SHA-256', 9, 'bold'); pdf.setFont('courier', 'normal'); text(r.integrityHash, 9, 'normal'); }
    else text('Draft record — not sealed. Content may still change.', 10, 'italic', [113, 113, 122]);
  }
  custom('footer');

  // Running footer
  const pages = pdf.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    pdf.setPage(p);
    pdf.setDrawColor(228, 228, 231); pdf.line(M, H - 40, W - M, H - 40);
    pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8); pdf.setTextColor(113, 113, 122);
    pdf.text(`${opts.classification} — ${PLATFORM_NAME} · ${r.id}`, M, H - 26);
    if (opts.includePageNumbers) pdf.text(`Page ${p} of ${pages}`, W - M, H - 26, { align: 'right' });
  }
  return pdf.output('blob');
};

